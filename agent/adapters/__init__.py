"""The services the agent drives, behind interfaces: the IP reservation
service, the DNS team's service (records and certificates), the F5, and a
probe that requests a page through a VIP. Only fakes exist so far; the real
ones wait on their APIs (docs/exposure-design.md, open questions 2, 3 and 6).
Every method is idempotent where the real service allows: the agent may
repeat a call after a restart."""
from dataclasses import dataclass
from typing import Any, Optional, Protocol


@dataclass(frozen=True)
class IssuedCertificate:
    """A certificate the DNS service issued, with its private key. The key goes
    to the F5 and nowhere else: never into a plan, a report or a log."""

    names: tuple[str, ...]
    certificate_pem: str
    private_key_pem: str
    expires: str  # ISO date


@dataclass(frozen=True)
class PartitionStatus:
    """What the F5 reports of a partition's objects: each virtual server's
    availability, and each pool's members, "address:port", up or not."""

    virtual_servers: dict[str, bool]
    pools: dict[str, dict[str, bool]]


@dataclass(frozen=True)
class ProbeResponse:
    status: int
    body: str


class IpReservations(Protocol):
    async def reserve(self, key: str, ranges: tuple[str, ...]) -> str:
        """An address from `ranges` held under `key`; the same one again for the same key."""

    async def release(self, key: str) -> None:
        """Release what `key` holds; nothing if it holds nothing."""


class DnsService(Protocol):
    async def issue_certificate(self, names: tuple[str, ...]) -> IssuedCertificate:
        """A certificate covering `names`, and its key, generated by the service."""

    async def create_record(self, zone: str, name: str, type: str, target: str) -> str:
        """Create a record, or find the same one already there; returns its id.
        Fails if the name exists pointing elsewhere: the agent never repoints one."""

    async def delete_record(self, zone: str, name: str, type: str, target: str) -> None:
        """Delete the record; nothing if it is not there, or points elsewhere."""


class F5(Protocol):
    async def install_certificate(self, partition: str, name: str, cert: IssuedCertificate) -> str:
        """Install a certificate and its key; returns its full path on the F5."""

    async def remove_certificate(self, path: str) -> None:
        """Remove an installed certificate; nothing if it is not there."""

    async def declaration(self, partition: str) -> Optional[dict[str, Any]]:
        """The AS3 declaration deployed to a partition, or None."""

    async def dry_run(self, partition: str, declaration: dict[str, Any]) -> list[str]:
        """Validate a declaration without deploying it: AS3's errors, empty if none."""

    async def deploy(self, partition: str, declaration: dict[str, Any]) -> None:
        """Post a declaration. AS3 applies it whole or not at all."""

    async def remove_partition(self, partition: str) -> None:
        """Remove a partition and everything in it; nothing if it is not there."""

    async def status(self, partition: str) -> PartitionStatus:
        """The availability of the partition's virtual servers and pool members."""


class Probe(Protocol):
    async def fetch(self, ip: str, host: str, path: str = "/") -> ProbeResponse:
        """Request `path` from a VIP's address, as `host` (the Host header and
        SNI), before any DNS name resolves to it."""
